"""Generate InstanceFactory extra defaults (InstanceFactory.extraDefaults in the Android app)."""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1]).read_text(encoding='utf-8')
out_path = pathlib.Path(sys.argv[2])
start = src.index('private final void extraDefaults')
body = src[start:]
consts = {'ItemTouchHelper.Callback.DEFAULT_DRAG_ANIMATION_DURATION': '200', 'PathInterpolatorCompat.MAX_NUM_POINTS': '3000',
          'Float.MAX_VALUE': 'Float.greatestFiniteMagnitude'}
for k, v in consts.items():
    body = body.replace(k, v)

def num(x):
    x = x.strip().rstrip('fFdDL')
    return x

def conv(e):
    e = e.strip()
    m = re.fullmatch(r'Float\.valueOf\((.+)\)', e)
    if m: return f'.float({num(m.group(1))})'
    if e in ('true', 'false'): return f'.bool({e})'
    if e == 'null': return '.ref(nil)'
    m = re.fullmatch(r'"([^"]*)"', e)
    if m: return f'.string("{m.group(1)}")'
    m = re.fullmatch(r'new EnumValue\((\d+)\)', e)
    if m: return f'.enumValue(EnumValue({m.group(1)}))'
    m = re.fullmatch(r'new Vector3\(([^,]+), ([^,]+), ([^,]+)\)', e)
    if m: return '.vector3(Vector3(%s, %s, %s))' % tuple(num(x) for x in m.groups())
    if e == 'v0': return '.vector3(.zero)'
    if e == 'Vector3.INSTANCE.getONE()': return '.vector3(.one)'
    m = re.fullmatch(r'Color3\.INSTANCE\.fromRGB\((\d+), (\d+), (\d+)\)', e)
    if m: return '.color3(.fromRGB(%s, %s, %s))' % m.groups()
    m = re.fullmatch(r'new Color3\(([^,]+), ([^,]+), ([^,]+)\)', e)
    if m: return '.color3(Color3(%s, %s, %s))' % tuple(num(x) for x in m.groups())
    if e == 'CFrame.INSTANCE.getIDENTITY()': return '.cframe(.identity)'
    m = re.fullmatch(r'new Vector2\(([^,]+), ([^,]+)\)', e)
    if m: return '.vector2(Vector2(%s, %s))' % tuple(num(x) for x in m.groups())
    m = re.fullmatch(r'new UDim2\(([^,]+), ([^,]+), ([^,]+), ([^,]+)\)', e)
    if m: return '.udim2(UDim2(%s, %s, %s, %s))' % tuple(num(x) for x in m.groups())
    m = re.fullmatch(r'new UDim\(([^,]+), ([^,]+)\)', e)
    if m: return '.udim(UDim(%s, %s))' % tuple(num(x) for x in m.groups())
    m = re.fullmatch(r'new BrickColorV\((\d+)\)', e)
    if m: return f'.brickColor(BrickColorV({m.group(1)}))'
    if e == 'new Ray(v0, v0)': return '.ray(Ray(.zero, .zero))'
    m = re.fullmatch(r'Integer\.valueOf\((-?\d+)\)', e)
    if m: return f'.int({m.group(1)})'
    if re.fullmatch(r'-?\d+', e): return f'.int({e})'
    return None

table = {}
current = []
skipped = 0
for line in body.splitlines():
    s = line.strip()
    if s.startswith('case ') or s.startswith('default:'):
        current = []
    for cls in re.findall(r'cls\.equals\("([A-Za-z0-9]+)"\)', s):
        if cls not in current: current.append(cls)
    m = re.match(r'extraDefaults\$s\(i, "([A-Za-z0-9_]+)", (.*)\);$', s)
    if m and current:
        v = conv(m.group(2))
        if v is None: skipped += 1; continue
        for cls in current:
            table.setdefault(cls, [])
            if all(k != m.group(1) for k, _ in table[cls]):
                table[cls].append((m.group(1), v))

lines = ['// Generated by tools/gen_defaults.py from the Android InstanceFactory.extraDefaults - do not edit.',
         'enum ExtraDefaults {', '    static func values(_ cls: String) -> [(String, PropValue)] {', '        switch cls {']
for cls in sorted(table):
    lines.append(f'        case "{cls}":')
    lines.append('            return [')
    for k, v in table[cls]:
        lines.append(f'                ("{k}", {v}),')
    lines.append('            ]')
lines += ['        default: return []', '        }', '    }', '}', '']
out_path.write_text('\n'.join(lines), encoding='utf-8')
print(len(table), 'classes,', sum(len(v) for v in table.values()), 'values,', skipped, 'skipped')
