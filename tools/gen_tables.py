"""Generate Swift lookup tables (BrickColors, Enums) from the decompiled Android sources."""
import re, sys, pathlib
clean = pathlib.Path(sys.argv[1]); out = pathlib.Path(sys.argv[2])
NAME_FIX = {'TypedValues.Custom.NAME': '"Custom"', 'ClothingCompositor.TORSO_H': '272', 'MaterialCardViewHelper.DEFAULT_FADE_ANIM_DURATION': '300', ', num)': ', 12)', ', num2)': ', 12)'}
def fix(s):
    for k, v in NAME_FIX.items(): s = s.replace(k, v)
    return s

# BrickColors
bc = (clean/'model/BrickColors.java').read_text(encoding='utf-8')
rows = re.findall(r'TuplesKt\.to\((\d+), TuplesKt\.to\("([^"]+)", (\d+)\)', bc)
lines = ['// Generated by tools/gen_tables.py - do not edit.', 'public enum BrickColorTable {',
         '    /// number -> (name, 0xRRGGBB), in original order', '    public static let entries: [(Int, String, Int)] = [']
lines += [f'        ({n}, "{nm}", 0x{int(c):06X}),' for n, nm, c in rows]
lines += ['    ]', '}', '']
(out/'BrickColorTable.swift').write_text('\n'.join(lines), encoding='utf-8')

# Enums
en = fix((clean/'model/Enums.java').read_text(encoding='utf-8'))
enums = {}
for name, body in re.findall(r'types\$lambda\$11\$e\(map, "(\w+)", (.*?)\);\n', en):
    enums[name] = [(k, int(v)) for k, v in re.findall(r'TuplesKt\.to\("(\w+)", (?:Integer\.valueOf\()?([-\w.]+?)\)?\)', body) if re.fullmatch(r'-?\d+', v)]
for name, body in re.findall(r'types\$lambda\$11\$seq\(map, "(\w+)", (.*?)\);\n', en):
    enums[name] = [(k, i) for i, k in enumerate(re.findall(r'"(\w+)"', body))]
lines = ['// Generated by tools/gen_tables.py - do not edit.', 'public enum EnumTable {',
         '    public static let types: [String: [(String, Int)]] = [']
for name in sorted(enums):
    items = ', '.join(f'("{k}", {v})' for k, v in enums[name])
    lines.append(f'        "{name}": [{items}],')
lines += ['    ]', '}', '']
(out/'EnumTable.swift').write_text('\n'.join(lines), encoding='utf-8')
print(len(rows), 'brickcolors;', len(enums), 'enums')

# ClassDb
cd = (clean/'model/ClassDb.java').read_text(encoding='utf-8')
pairs = []
for base, rest in re.findall(r'parents\$lambda\$0\$p\(map, "(\w+)", (.*?)\);', cd):
    for c in re.findall(r'"([\w ]+)"', rest): pairs.append((c, base))
def strlist(var):
    m = re.search(var + r' = .*?(?:listOf|setOf)\(\(Object\[\]\) new String\[\]\{(.*?)\}', cd, re.S)
    return re.findall(r'"(\w+)"', m.group(1))
svc, other, ins = strlist('serviceNames'), strlist('otherServices'), strlist('insertable')
lines = ['// Generated by tools/gen_tables.py - do not edit.', 'enum ClassDbTable {',
         '    /// (class, superclass) in original insertion order; later entries override earlier ones.',
         '    static let parents: [(String, String)] = [']
lines += [f'        ("{c}", "{b}"),' for c, b in pairs]
lines += ['    ]', '    static let serviceNames: [String] = [' + ', '.join(f'"{s}"' for s in svc) + ']',
          '    static let otherServices: Set<String> = [' + ', '.join(f'"{s}"' for s in other) + ']',
          '    static let insertable: [String] = [' + ', '.join(f'"{s}"' for s in sorted(set(ins))) + ']', '}', '']
(out/'ClassDbTable.swift').write_text('\n'.join(lines), encoding='utf-8')
print(len(pairs), 'class parents;', len(svc), len(other), len(set(ins)))
